"""Recheck the numerical convergence of selected, frozen ElasticNet forecasts.

Run after ``scripts/complete_tuning.py`` has produced the original four search
panels. This diagnostic never changes model selection, forecast caches, or
investment parameters. It compares the default solver with a stricter solver
at every early validation date and at declared later calendar checkpoints.
"""
import argparse
import hashlib
import json
from pathlib import Path
import pickle
import sys
import warnings

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np
import pandas as pd
import sklearn
from sklearn.exceptions import ConvergenceWarning
from sklearn.linear_model import ElasticNet

from bond_rp.tuning_search import predict_config
from bond_rp.validated_models import gaussian_augment


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def strict_predict(fold, config):
    """Independent four-maturity fit with tighter solver stopping criteria."""
    X = fold["X"][config["representation"]]
    x = fold["x"][config["representation"]]
    y = fold["y"]
    location = y.mean(axis=0)
    scale = np.maximum(y.std(axis=0), 1e-8)
    normalized = (y-location)/scale
    if config["gc_ratio"] > 0:
        X, normalized = gaussian_augment(X, normalized, seed=42, ratio=config["gc_ratio"])
    values = np.column_stack([
        ElasticNet(max_iter=300000, tol=1e-6, **config["params"])
        .fit(X, normalized[:, j]).predict(x) for j in range(4)
    ])
    return values*scale+location


def run_with_warning_count(function, fold, config):
    with warnings.catch_warnings(record=True) as found:
        warnings.simplefilter("always", ConvergenceWarning)
        values = function(fold, config)
    if not np.isfinite(values).all():
        raise ValueError("Selected model generated a nonfinite forecast during solver audit")
    return values, sum(issubclass(w.category, ConvergenceWarning) for w in found)


def audit_models(output_dir):
    output_dir = Path(output_dir)
    sources = ["bond_rp/tuning_search.py", "bond_rp/tuning_features.py", "bond_rp/validated_models.py"]
    report = dict(
        purpose="Independent numerical-solver check of already selected EN models; no re-selection",
        source_sha256={path: sha256(ROOT/path) for path in sources},
        script_sha256=sha256(__file__),
        versions=dict(numpy=np.__version__, pandas=pd.__version__, sklearn=sklearn.__version__),
        strict_solver=dict(max_iter=300000, tol=1e-6),
        default_solver=dict(max_iter=100000, tol=1e-5),
        strict_sample_rule="All early validation purchase dates with labels strictly before 2014-01, every January, and March 2020",
        prediction_difference_unit="percentage points of predicted excess return",
        models=[],
    )
    for panel in ("core_revised", "headline_vintage"):
        for horizon in (1, 12):
            folder = output_dir/panel/f"h{horizon}"
            cache = folder/"folds.pkl"
            if not cache.exists():
                raise FileNotFoundError(f"Missing {cache}; run complete_tuning.py for all four search panels first")
            # This is the trusted local cache generated by the project's runner.
            with cache.open("rb") as source:
                folds = pickle.load(source)
            for model in ("EN_real", "EN_GC"):
                trial_path = folder/f"{model}_validation_trials.csv"
                table = pd.read_csv(trial_path)
                winner = table.loc[table.value.idxmin()]
                config = json.loads(winner.config)
                state = lambda: dict(folds=0, default_warning_count=0, strict_folds=0,
                                     strict_warning_count=0, max_abs_prediction_difference=0.)
                entry = dict(
                    panel=panel, horizon=horizon, model=model, config=config,
                    config_sha256=hashlib.sha256(json.dumps(config, sort_keys=True).encode()).hexdigest(),
                    fold_cache_sha256=sha256(cache), trial_csv_sha256=sha256(trial_path),
                    early=state(), later=state(), default_warning_dates=[],
                    strict_warning_dates=[], strict_differences=[],
                )
                for date, fold in folds[config["window"]].items():
                    early = date+fold["audit"]["horizon"] < pd.Period("2014-01", "M")
                    block = entry["early" if early else "later"]
                    block["folds"] += 1
                    default, count = run_with_warning_count(predict_config, fold, config)
                    block["default_warning_count"] += count
                    if count:
                        entry["default_warning_dates"].append(dict(ym=str(date), warnings=count))
                    if early or date.month == 1 or date == pd.Period("2020-03", "M"):
                        strict, count = run_with_warning_count(strict_predict, fold, config)
                        block["strict_folds"] += 1
                        block["strict_warning_count"] += count
                        if count:
                            entry["strict_warning_dates"].append(dict(ym=str(date), warnings=count))
                        difference = float(np.max(np.abs(default-strict)))
                        block["max_abs_prediction_difference"] = max(block["max_abs_prediction_difference"], difference)
                        entry["strict_differences"].append(dict(ym=str(date), max_abs_prediction_difference=difference))
                report["models"].append(entry)
                print(f"{panel}/h{horizon} {model}: early={entry['early']}, later={entry['later']}", flush=True)
    report["summary"] = dict(
        selected_models=len(report["models"]),
        default_forecast_folds=sum(m[b]["folds"] for m in report["models"] for b in ("early", "later")),
        stricter_forecast_folds=sum(m[b]["strict_folds"] for m in report["models"] for b in ("early", "later")),
        default_warning_count=sum(m[b]["default_warning_count"] for m in report["models"] for b in ("early", "later")),
        strict_warning_count=sum(m[b]["strict_warning_count"] for m in report["models"] for b in ("early", "later")),
        max_abs_prediction_difference=max(m[b]["max_abs_prediction_difference"] for m in report["models"] for b in ("early", "later")),
    )
    target = output_dir/"selected_en_convergence.json"
    temporary = target.with_suffix(".json.tmp")
    temporary.write_text(json.dumps(report, indent=2))
    temporary.replace(target)
    print(f"Saved {target}", flush=True)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT/"output"/"completed_tuning")
    args = parser.parse_args()
    audit_models(args.output_dir)


if __name__ == "__main__":
    main()
